package com.turkey.quick.location.dto;

/**
 * 위치 갱신 요청 한 건의 판정 결과. 응답의 {@code reason} 으로 그대로 나간다.
 *
 * 여기 있는 값은 모두 <b>HTTP 200</b> 으로 응답되는 경우다. 좌표 범위 밖·필수 값 누락·미래
 * 시각·정확도 음수처럼 클라이언트가 고쳐야 하는 요청은 판정 대신 400 으로 끊기므로 이 enum 에
 * 나타나지 않는다. 그 경계를 왜 이렇게 그었는지는 #234 참고 — 실내 측위나 탭 복귀 직후처럼
 * 정상적으로 발생하는 환경 조건을 4xx 로 만들면 라이더 화면이 정상 상황에서 에러를 기록한다.
 *
 * 값은 이 이슈가 실제로 만들어내는 것만 둔다. 중복·이상 이동 판정(#82)은 그 이슈에서 자기 값을
 * 추가한다 — 지금 미리 넣으면 아무도 만들지 않는 값이 계약에 노출된다.
 */
public enum LocationUpdateOutcome {

    /** 검증을 통과했다. 저장·전파 대상이다. */
    ACCEPTED,

    /** 측정 시각이 너무 오래됐다. "현재 위치"로 볼 수 없어 버린다. */
    STALE,

    /** 정확도가 기준에 못 미친다. 지도가 튀고 배차 거리 계산이 틀어지므로 버린다. */
    LOW_ACCURACY,

    /**
     * 이전 최신 위치보다 측정 시각이 과거이거나 같다. 순서가 뒤바뀌어 도착한 요청이나 재전송이며,
     * 받아들이면 "최신 위치"가 과거로 되돌아간다.
     */
    NON_MONOTONIC,

    /**
     * 이전 위치에서 의미 있게 움직이지 않았다(#82). <b>저장은 하고 전송만 생략한다</b> —
     * 정지한 라이더도 Redis 키 TTL 을 갱신해야 배차 후보 검색(#83)에서 빠지지 않지만, 고객 지도에
     * 같은 좌표를 다시 밀 이유는 없다. 이 값만 "폐기"가 아니라 "저장하되 전파하지 않음"이다.
     */
    DUPLICATE,

    /**
     * 이전 위치에서 물리적으로 불가능한 속도로 이동했다(#82). 측위 오류로 보고 저장하지 않는다 —
     * 저장하면 잘못된 좌표가 다음 판정의 기준이 된다.
     */
    IMPLAUSIBLE_SPEED;

    /**
     * Redis 최신 위치를 갱신할 판정인가.
     *
     * {@link #DUPLICATE} 가 유일하게 "저장은 하되 전송하지 않는" 값이라, 저장 여부와 전송 여부를
     * 한 메서드로 물을 수 없다. 둘을 합치면 정지한 라이더의 TTL 이 갱신되지 않아 배차 후보에서
     * 빠지거나(전송 기준으로 합치면), 같은 좌표가 고객 지도로 계속 밀린다(저장 기준으로 합치면).
     */
    public boolean shouldStore() {
        return this == ACCEPTED || this == DUPLICATE;
    }

    /** 구독 중인 고객에게 전송할 판정인가. */
    public boolean shouldPublish() {
        return this == ACCEPTED;
    }
}
