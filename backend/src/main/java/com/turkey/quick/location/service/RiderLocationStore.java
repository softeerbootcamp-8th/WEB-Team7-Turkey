package com.turkey.quick.location.service;

import com.turkey.quick.location.dto.RiderLocationSnapshot;
import java.util.Optional;

/**
 * 라이더 최신 위치의 저장소. 운영에서는 Redis(TTL)를 쓰고, 통합·E2E 테스트에서는 로컬 Redis 없이
 * 돌 수 있도록 인메모리 구현으로 대체한다({@code SessionStore}·{@code VerificationCodeStore}와
 * 같은 이유).
 *
 * 최신 위치의 정본은 Redis 다(docs/02-domain-policy.md §7). MySQL
 * ({@code rider_location_history})에는 장기 보관이 필요한 이력만 선별 저장하며(#102) 최신 위치
 * 조회 경로로 쓰지 않는다.
 *
 * TTL 을 파라미터로 받지 않는 이유: 세션 TTL(2시간)은 로그인 정책이라 호출자가 정할 일이지만
 * (그래서 {@code SessionStore.create} 는 받는다), 최신 위치의 유효 시간은 이 저장소의 인프라
 * 성질이다. 호출자가 매번 넘기면 서비스마다 다른 값이 들어갈 통로가 생긴다.
 *
 * {@code delete} 가 없는 것은 의도적이다. 운행 종료 시 최신 위치를 즉시 지우는 것이 맞지만
 * 그 API(운행 상태 변경)가 아직 구현되지 않아 부를 곳이 없다. 그 이슈에서 함께 추가한다.
 * 그때까지는 TTL 이 대신 정리하므로 <b>운행 종료 후 최대 TTL 만큼 배차 후보에 남는 틈</b>이
 * 있다 — 알고 있는 한계다.
 */
public interface RiderLocationStore {

    /**
     * 저장된 값보다 측정 시각이 <b>최신일 때만</b> 라이더의 최신 위치를 저장하고 TTL 을 다시 건다.
     * 조회·비교·쓰기가 하나의 원자적 연산이어야 한다(#250).
     *
     * <p>무조건 덮어쓰는 연산을 두지 않은 이유: 그것과 이것을 함께 두면 다음 사람이 더 짧은
     * 이름을 고르고, 수평 확장에서 같은 라이더의 요청 둘이 다른 인스턴스에서 처리될 때
     * <b>오래된 좌표가 최신을 덮는다</b>. 그건 조용히 일어나고(응답은 200) 다음 이벤트가 복구하므로
     * 테스트로도 잘 드러나지 않는다. 애초에 부를 수 없게 두는 편이 낫다.
     *
     * <p>구현이 지켜야 하는 의미론:
     * <ul>
     *   <li>저장된 값이 없으면(만료 포함) 무조건 쓴다.</li>
     *   <li>측정 시각이 <b>같으면</b> 쓰지 않는다 — 재전송이라 값은 같은데 쓰기만 늘어난다.</li>
     *   <li>저장된 값이 손상돼 시각을 읽을 수 없으면 새 값으로 덮는다. 해석할 수 없는 값을 남기면
     *       {@link #find} 가 계속 빈 결과를 주고, 그 라이더는 TTL 이 만료될 때까지 기준선 없이 돈다.</li>
     * </ul>
     *
     * @return 실제로 저장했는지. false 면 저장된 값이 이 위치보다 최신이거나 같다는 뜻이다
     */
    boolean saveIfNewer(Long riderId, RiderLocationSnapshot location);

    /**
     * 최신 위치가 있으면 반환한다. 저장된 적이 없거나 TTL 로 만료됐으면 빈 결과다.
     * 저장된 값이 손상돼 해석할 수 없는 경우도 빈 결과로 취급한다 — 잘못된 좌표를 배차·추적에
     * 흘리는 것보다 "위치 없음"이 낫다.
     */
    Optional<RiderLocationSnapshot> find(Long riderId);

    /**
     * 저장된 값은 그대로 두고 TTL 만 다시 건다(#82 중복 판정).
     *
     * <p>의미 있게 움직이지 않은 좌표를 <b>저장하지 않고 TTL 만 갱신하는</b> 이유: 새 좌표로
     * 덮으면 기준선이 조금씩 전진해서, 느리게 움직이는 라이더는 매번 "직전 대비 몇 m"만 이동한
     * 것이 되어 영원히 전송 대상이 되지 않는다(고객 지도의 마커가 얼어붙는다). 기준선을 고정하면
     * 누적 이동이 최소 이동 거리를 넘는 순간 전송된다. 대가는 저장된 최신 위치가 실제 위치보다
     * 최소 이동 거리만큼 뒤처질 수 있다는 것인데, 배차 반경이 km 단위라 무의미하다.
     *
     * @return 갱신할 값이 실제로 있었는지. 조회와 이 호출 사이에 TTL 이 만료됐으면 false 이며,
     *         그 경우 다음 위치 갱신이 최초 좌표로 저장하므로 자연히 복구된다
     */
    boolean refreshTtl(Long riderId);
}
